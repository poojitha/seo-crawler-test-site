// Writes PAGES.md from the route registry (expected-results.csv comes from npm run expected).
// Usage: npm run pages
const fs = require('fs');
const path = require('path');
require('../src/routes');
const { CATS, tests } = require('../src/registry');

const root = path.join(__dirname, '..');
const rows = tests();
const md = (s) => String(s || '').replace(/\|/g, '\|').replace(/\n/g, ' ');

let out = `# Page list\n\nGenerated by \`npm run pages\` – ${rows.length} test URLs in ${CATS.length} categories.\n` +
  `"Linked" = reachable through normal <a> links from the home page. Unlinked URLs must be discovered another way.\n\n`;
out += '| Category | URLs |\n|---|---|\n' + CATS.map(([k, l]) => `| [${l}](#${k}) | ${rows.filter((r) => r.cat === k).length} |`).join('\n') + '\n\n';
for (const [cat, label, desc] of CATS) {
  out += `## ${label}\n<a id="${cat}"></a>\n\n${desc}\n\n| URL | Tests | Expected crawler result | Linked |\n|---|---|---|---|\n`;
  for (const r of rows.filter((x) => x.cat === cat)) out += `| \`${md(r.href.length > 90 ? r.href.slice(0, 87) + '…' : r.href)}\` | ${md(r.test)} | ${md(r.expect)} | ${r.listed ? 'yes' : 'no'} |\n`;
  out += '\n';
}
fs.writeFileSync(path.join(root, 'PAGES.md'), out);

console.log(`Wrote PAGES.md (${rows.length} URLs)`);
